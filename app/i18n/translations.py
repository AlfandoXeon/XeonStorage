def get_translator(lang_code: str = "en"):
    lang = lang_code.lower() if lang_code else "en"
    if lang not in TRANSLATIONS:
        lang = "en"
    
    dict_trans = TRANSLATIONS[lang]
    
    def translate(key: str, default: str = None, **kwargs) -> str:
        text = dict_trans.get(key, TRANSLATIONS["en"].get(key, default or key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    return translate, lang
